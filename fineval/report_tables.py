"""Generate report/numbers.tex (one macro per figure) and report/tables/*.tex from result files.

    python -I -m fineval.report_tables

report/main.tex contains no typed figures: tests/test_report.py checks that every number in its
prose comes from these generated macros or tables.
"""
import json

from .build import OUT as DATA
from .export import PUBLISHED_MAP, SOURCE_NAME, published_rows, reproduced_rows
from .fetch import ROOT, load_manifest
from .sources.registry import SOURCES

REPORT = ROOT / "report"
TABLES = REPORT / "tables"
RESULTS = ROOT / "results"


def _read(p):
    return json.loads(p.read_text(encoding="utf-8"))


def tex(s) -> str:
    return (str(s).replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")
            .replace("#", r"\#").replace("$", r"\$").replace("{", r"\{").replace("}", r"\}"))


def num(n) -> str:
    return f"{n:,}".replace(",", "{,}")


def pct(v) -> str:
    return f"{100 * v:.1f}"


def _table(name, colspec, header, rows, caption=None):
    body = "\n".join(" & ".join(r) + r" \\" for r in rows)
    TABLES.mkdir(parents=True, exist_ok=True)
    (TABLES / f"{name}.tex").write_text(
        f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n{' & '.join(header)} \\\\\n\\midrule\n{body}\n\\bottomrule\n\\end{{tabular}}\n",
        encoding="utf-8")


def main():
    s, ov = _read(DATA / "summary.json"), _read(DATA / "overlap.json")
    conf = _read(DATA / "conflicts.json")
    retr = {p.stem: _read(p) for p in (RESULTS / "retrieval").glob("*.json")}
    sft = _read(DATA / "sft" / "stats.json") if (DATA / "sft" / "stats.json").exists() else {}
    m = load_manifest()
    rep = reproduced_rows()

    macros = {
        "nSourceItems": num(s["records_loaded"]), "nSkipped": num(s["rows_skipped"]), "nUnique": num(s["clusters"]),
        "nMulti": num(s["multi_member_clusters"]), "nJoinExact": num(s["joins"]["exact_text"]),
        "nJoinId": num(s["joins"]["same_source_id"]), "nConflicts": num(len(conf)),
        "nReview": num(s["review_pairs"]), "nReviewPending": num(s["review_pending"]),
        "nPinned": num(len(m)), "nSources": num(len(SOURCES)),
        "nTrainDropped": num(sum(s["train_dropped"].values())),
        "nTagTest": num(s["items"]["concept_tagging:test"]), "nTagPrimary": num(s["primary_items"]["concept_tagging:test"]),
        "nFactTest": num(s["items"]["fact_extraction:test"]), "nCalcTest": num(s["items"]["financial_calc:test"]),
        "nQATest": num(s["items"]["filing_qa:test"]), "nTermTest": num(s["items"]["terminology:test"]),
        "nFactTrain": num(s["items"]["fact_extraction:train"]),
        "nAmbiguousTag": num(s["flags"].get("concept_tagging:ambiguous", 0)),
        "nSourceDisagreeQA": num(s["flags"].get("filing_qa:source_disagreement", 0)),
        "nReproducedRows": num(len(rep)), "nPublishedRows": num(len(published_rows())),
    }
    for k, name in (("finni_examples", "nSftFinni"), ("fincl_examples", "nSftFincl"),
                    ("fincl_entities_without_locatable_context", "nSftNoContext")):
        if k in sft:
            macros[name] = num(sft[k])
    tax = retr.get("taxonomy", {})
    for name, key in (("fincl_subset", "Fincl"), ("fincl_subset+type", "FinclType"), ("tag_query", "Tag")):
        for k in ("acc@1", "acc@50", "acc@200"):
            if name in tax:
                macros[f"ret{key}{k.replace('acc@', 'At').replace('1', 'One').replace('50', 'Fifty').replace('200', 'TwoHundred')}"] = pct(tax[name][k]["value"])
    if "formulas" in retr:
        macros["retFormula"] = pct(retr["formulas"]["xbrl_agent_formula"]["acc@1"]["value"])
    if "filings" in retr:
        f = retr["filings"]["financebench_open"]
        macros["retPageThree"] = pct(f["recall@3"]["value"])
        macros["retPageTen"] = pct(f["recall@10"]["value"])
    REPORT.mkdir(parents=True, exist_ok=True)
    (REPORT / "numbers.tex").write_text(
        "% generated by python -I -m fineval.report_tables; do not edit\n"
        + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(macros.items())) + "\n", encoding="utf-8")
    (REPORT / "numbers.json").write_text(json.dumps(macros, indent=1), encoding="utf-8")

    _table("sources", "p{3.1cm}lr", ["Source", "Licence", "Files"],
           [[tex(v["title"]), tex(v["licence"]), num(sum(1 for x in m if x.startswith(k + "/")))] for k, v in SOURCES.items()])

    rows = [[tex(d.replace(":test", "").replace(":validation", " (val)")), tex(info["task"].replace("_", " ")), num(info["size"])]
            for d, info in sorted(ov["datasets"].items(), key=lambda kv: (kv[1]["task"], kv[0]))]
    _table("datasets", "llr", ["Dataset", "Task", "Items"], rows)

    full = [p for p in ov["pairs"] if p["share"] >= 0.999]
    _table("containment", "llr", ["Dataset", "Contained in", "Items"],
           [[tex(p["dataset"]), tex(p["in_dataset"]), f"{num(p['overlap'])}/{num(p['size'])}"] for p in full])

    _table("benchmark", "lrr", ["Task : split", "Items", "Primary"],
           [[tex(k.replace("_", " ")), num(v), num(s["primary_items"][k])] for k, v in s["items"].items()])

    _table("conflicts", "llr", ["Task", "Kind", "Clusters"],
           [[tex(k.split(":")[0].replace("_", " ")), tex(k.split(":")[1].replace("_", " ")), num(v)] for k, v in sorted(s["conflicts"].items())])

    tr = []
    for name in ("fincl_subset", "fincl_subset+type", "tag_query"):
        if name in tax:
            tr.append([tex(name), num(tax[name]["n"])] + [pct(tax[name][f"acc@{k}"]["value"]) for k in (1, 10, 50, 100, 200)])
    _table("retrieval", "lrrrrrr", ["Setting", "n", "@1", "@10", "@50", "@100", "@200"], tr)

    pub = published_rows()
    for block, label in SOURCE_NAME.items():
        maps = [(m_, t) for b, m_, t, *_ in PUBLISHED_MAP if b == block]
        models = list(dict.fromkeys(r["model"] + (f" ({r['setting']})" if r["setting"] else "") for r in pub if
                                    any(r["metric"] == m_ and r["task"] == t for m_, t in maps)))
        rows = []
        for mod in models:
            cells = []
            for m_, t in maps:
                r = next((r for r in pub if r["metric"] == m_ and r["task"] == t and
                          r["model"] + (f" ({r['setting']})" if r["setting"] else "") == mod), None)
                cells.append(pct(r["value"]) if r else "--")
            rows.append([tex(mod)] + cells)
        _table(f"published_{block}", "l" + "r" * len(maps), ["Model"] + [tex(m_.replace("_", " ")) for m_, _ in maps], rows)

    if rep:
        _table("reproduced", "llllr", ["Model", "Task", "Track", "n", "Score [95\\% CI]"],
               [[tex(r["model"]), tex(r["task"].replace("_", " ")), r["track"], num(r["n"]),
                 f"{pct(r['value'])} [{pct(r['ci95'][0])}, {pct(r['ci95'][1])}]"] for r in rep])
    print(f"wrote {len(macros)} macros and {len(list(TABLES.glob('*.tex')))} tables")


if __name__ == "__main__":
    main()
