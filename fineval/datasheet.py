"""Write docs/datasheet.md from the manifest and the built benchmark. Every number in it is
computed here from files; nothing is typed by hand.

    python -I -m fineval.datasheet
"""
import json
from collections import Counter

from .build import OUT
from .fetch import ROOT, load_manifest
from .sources.registry import GATED_HF, SOURCES

DOC = ROOT / "docs" / "datasheet.md"


def _load(name):
    return json.loads((OUT / name).read_text(encoding="utf-8"))


def main():
    s, ov, conf = _load("summary.json"), _load("overlap.json"), _load("conflicts.json")
    skipped, dropped = _load("skipped.json"), _load("dropped.json")
    m = load_manifest()
    L = ["# FinEval v1 datasheet", "",
         "*Generated by `python -I -m fineval.datasheet` from `data/raw/MANIFEST.json` and `data/v1/`. "
         "Do not edit by hand.*", "", "## Sources", "",
         "| Source | Repository @ commit | Licence | Files |", "|---|---|---|---|"]
    for k, v in SOURCES.items():
        L.append(f"| {v['title']} | `{v['repo']}` @ `{v['commit'][:10]}` | {v['licence']} | {len(v['files'])} |")
    L += ["", f"{len(m)} files are pinned by SHA-256 in `data/raw/MANIFEST.json`.", "",
          "**Not used in v1 (gated on Hugging Face; access requires the account owner to submit a form):** "
          + ", ".join(f"`{k}`" for k in GATED_HF) + ". FinTagging's released GitHub subsets "
          "(FinCL 500 rows, FinNI 200 rows) are used instead.", "",
          "## Items per dataset (before de-duplication)", "", "| Task | Dataset (source:subset:split) | Items |", "|---|---|---|"]
    for ds, d in sorted(ov["datasets"].items(), key=lambda kv: (kv[1]["task"], kv[0])):
        L.append(f"| {d['task']} | `{ds}` | {d['size']} |")
    L += ["", f"Rows that could not become items: {len(skipped)} "
          f"({', '.join(f'{n} × {r}' for r, n in Counter(x['reason'] for x in skipped).items())}).", "",
          "## Overlap between datasets", "",
          "Share of dataset A's items that also appear in dataset B (exact normalised text or the same FinanceBench id).", "",
          "| Task | A | B | Overlap | Share of A |", "|---|---|---|---|---|"]
    for r in ov["pairs"]:
        L.append(f"| {r['task']} | `{r['dataset']}` | `{r['in_dataset']}` | {r['overlap']} / {r['size']} | {r['share']:.1%} |")
    L += ["", "## Benchmark after de-duplication", "",
          f"{s['records_loaded']} source items form {s['clusters']} unique items "
          f"({s['multi_member_clusters']} items exist in more than one place). "
          f"Joins: {', '.join(f'{v} by {k}' for k, v in s['joins'].items())}.", "",
          "| Task : split | Items | In primary score |", "|---|---|---|"]
    for k, n in s["items"].items():
        L.append(f"| {k} | {n} | {s['primary_items'][k]} |")
    L += ["", "## Gold-answer conflicts", "",
          "Duplicates whose gold answers disagree after normalisation. Policy (see `fineval/splits.py`): "
          "cross-source disagreements keep the original publisher's answer and stay in the score; "
          "identical inputs with different answers inside one dataset are marked *ambiguous* and excluded "
          "from the primary score; conflicting training items are dropped.", "",
          "| Task | Kind | Clusters |", "|---|---|---|"]
    for k, n in sorted(s["conflicts"].items()):
        t, kind = k.split(":")
        L.append(f"| {t} | {kind} | {n} |")
    fqa = [c for c in conf if c["task"] == "filing_qa"]
    if fqa:
        L += ["", "Filing-QA disagreements (original vs copies):", ""]
        for c in fqa:
            for g, uids in c["golds"].items():
                L.append(f"- `{', '.join(uids)}`: {g[4:120]}…")
    L += ["", "## Leakage control", "",
          f"- Training items dropped: {', '.join(f'{v} × {k}' for k, v in s['train_dropped'].items()) or 'none'}.",
          f"- Near-duplicate pairs awaiting human review (`review/near_dups.csv`): {s['review_pending']} of "
          f"{s['review_pairs']}. Until decided they are treated as possible duplicates for leakage purposes.",
          "- Validation items from a filing that is also in the test set are flagged `filing_in_test`; "
          "few-shot selection never shows an example from the test item's own filing.",
          "- FinTagging's release has no filing identifiers, so filing-level overlap between FinTagging and "
          "the COLING tag queries cannot be measured; text-level overlap is 0.", ""]
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)} ({len(L)} lines, {len(dropped)} dropped rows listed in data/v1/dropped.json)")


if __name__ == "__main__":
    main()
