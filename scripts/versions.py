"""Write docs/VERSIONS.md: every code, data, runtime and model version behind the reported results.

    python -I scripts/versions.py

Everything is read from files (data/raw/MANIFEST.json, results/generations/*.meta.json,
requirements.lock.txt), so the note can be regenerated after every new run.
"""
import json
import platform
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from fineval import run  # noqa: E402


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True).stdout.strip()



def show(model):
    """Quantisation level and parameter size from the local Ollama, or 'not installed'."""
    import urllib.request
    try:
        req = urllib.request.Request("http://localhost:11434/api/show", data=json.dumps(
            {"model": model.removeprefix("ollama:")}).encode(), headers={"Content-Type": "application/json"})
        d = json.loads(urllib.request.urlopen(req, timeout=10).read())["details"]
        return d.get("quantization_level", "?"), d.get("parameter_size", "?")
    except Exception:
        return "not installed", "?"

def main():
    manifest = json.loads((ROOT / "data/raw/MANIFEST.json").read_text(encoding="utf-8"))
    sources = defaultdict(set)
    for v in manifest.values():
        key = v.get("repo") or v.get("source")
        sources[(v.get("source"), key, v.get("commit") or v.get("revision") or "", v.get("licence", ""))].add(v.get("path", ""))
    metas = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(run.GEN.glob("*.meta.json"))]
    models = defaultdict(set)
    runtimes = defaultdict(set)
    commits = defaultdict(set)
    for m in metas:
        models[m["model"]].add(m.get("model_digest") or "unrecorded")
        runtimes[m["model"]].add(m.get("runtime") or "unrecorded")
        commits[(m.get("code_commit") or "unrecorded")[:7]].add(f'{m["model"]} {m["task"]} {m["track"]}')

    head = git("rev-parse", "HEAD")
    lines = ["# Versions behind the results", "",
             "Generated by `python -I scripts/versions.py`; do not edit by hand.", "",
             "## Our code", "",
             f"- Repository: https://github.com/Quantum-Coded/xbrl-leaderboard, commit at generation `{head[:12]}`",
             f"- Python {platform.python_version()} (lock file: `requirements.lock.txt`)", "",
             "Code commit recorded in each run's meta file:", "",
             "| Commit | Runs |", "|---|---|"]
    for c, rs in sorted(commits.items()):
        lines.append(f"| `{c}` | {len(rs)} runs |")
    lines += ["", "## Data sources (pinned)", "", "| Source | Repository / origin | Commit | Licence | Files |",
              "|---|---|---|---|---|"]
    for (src, repo, commit, lic), paths in sorted(sources.items(), key=lambda x: [str(t) for t in x[0]]):
        lines.append(f"| {src} | {repo} | `{commit}` | {lic} | {len(paths)} |")
    lines += ["", "## Models and runtime (from run meta files)", "",
              "| Model | Ollama digest | Runtime | Quantisation | Parameters |", "|---|---|---|---|---|"]
    for m in sorted(models):
        q, n = show(m)
        lines.append(f"| `{m}` | {', '.join(f'`{d[:12]}`' for d in sorted(models[m]))} | "
                     f"{', '.join(sorted(runtimes[m]))} | {q} | {n} |")
    lines += ["", "Quantisation and parameter count are read from the local Ollama (`/api/show`) when this file is "
              "generated. All runs decode greedily (temperature 0, seed 0).", ""]
    dest = ROOT / "docs" / "VERSIONS.md"
    dest.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
